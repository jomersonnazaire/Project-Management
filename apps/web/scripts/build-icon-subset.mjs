// Regenerates src/vendor/sneat/icons.css: the Boxicons this app uses, as CSS mask rules with
// inline SVGs, taken from the full Boxicons set (bx, bxs, bxl; Boxicons 2.1.4 via Iconify) that
// Sneat free v3.0.0 ships as `assets/vendor/fonts/iconify-icons.css` (MIT). A gzipped copy of that
// file is kept in scripts/vendor so this runs offline; we don't ship all 1.3 MB to the browser.
//
// Included: every `bx-` / `bxs-` / `bxl-` class found in src (outside vendor/ and test/), plus
// src/vendor/sneat/icons.required.json. src/test/icons.test.ts fails if anything is missing.
//
// Usage: node scripts/build-icon-subset.mjs [path-to-iconify-icons.css]
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gunzipSync } from 'node:zlib';

const root = fileURLToPath(new URL('..', import.meta.url));
const srcDir = join(root, 'src');
const source = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : gunzipSync(readFileSync(join(root, 'scripts/vendor/sneat-iconify-icons.css.gz'))).toString();

export const ICON_CLASS = /\b(bx[sl]?-[a-z0-9]+(?:-[a-z0-9]+)*)\b/g;

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name !== 'vendor' && name !== 'test') yield* files(p);
    } else if (/\.(tsx?|s?css|html)$/.test(name)) yield p;
  }
}

const used = new Set();
for (const f of files(srcDir))
  for (const m of readFileSync(f, 'utf8').matchAll(ICON_CLASS)) used.add(m[1]);
const required = JSON.parse(
  readFileSync(join(srcDir, 'vendor/sneat/icons.required.json'), 'utf8'),
).icons;
const names = [...new Set([...used, ...required])].sort();

const base = /^\.bx \{[^}]*\}/m.exec(source);
if (!base) throw new Error('.bx base rule not found');
const out = [
  '/* Boxicons (MIT, © Atisa, https://boxicons.com) as CSS masks, generated by',
  '   scripts/build-icon-subset.mjs from Sneat free v3.0.0 iconify-icons.css (MIT, see LICENSE).',
  '   Do not edit by hand: add the class in src (or icons.required.json) and re-run the script. */',
  base[0],
];
const missing = [];
for (const name of names) {
  const m = new RegExp(`^\\.${name} \\{[^}]*\\}`, 'm').exec(source);
  if (m) out.push(m[0]);
  else missing.push(name);
}
if (missing.length) throw new Error(`Not in Boxicons: ${missing.join(', ')}`);
writeFileSync(join(srcDir, 'vendor/sneat/icons.css'), out.join('\n\n') + '\n');
console.log(`Wrote ${names.length} icons`);
