describe('TC-R07/R09: saved reports', () => {
  it('lists Latest, Earlier version and untagged overlaps; opens the read-only copy', async () => {
    const items = [
      summary({ id: 's1' }),
      summary({
        id: 's2',
        savedAt: '2026-10-02T10:20:00.000Z',
        tag: 'EARLIER',
        changedDates: ['2026-10-01'],
      }),
      summary({ id: 's3', from: '2026-10-01', tag: null }),
    ];
    api('MEMBER', (url) => {
      if (url.includes('/dar/saved/s2'))
        return { status: 200, body: { item: { ...items[1], report: report() } } };
      if (url.includes('/dar/saved')) return { status: 200, body: { items } };
      return undefined;
    });
    renderAt('/dar/saved', <App />);
    const rows = await screen.findAllByRole('row');
    expect(rows[1]).toHaveTextContent('Oct 3, 2026');
    expect(rows[1]).toHaveTextContent('Sep 30 – Oct 2');
    expect(rows[1]).toHaveTextContent('Latest');
    expect(rows[2]).toHaveTextContent('Earlier version');
    expect(rows[2]).toHaveTextContent('Changed after saving');
    expect(rows[3]).toHaveTextContent('Oct 1 – Oct 2');
    expect(rows[3]).not.toHaveTextContent(/Latest|Earlier/);
    // No edit or delete anywhere (FR-DAR-15).
    expect(screen.queryByRole('button', { name: /delete|edit/i })).not.toBeInTheDocument();
    await userEvent.click(within(rows[2]!).getByRole('button', { name: 'View' }));
    const dialog = await screen.findByRole('dialog');
    expect(within(dialog).getByText('Read-only')).toBeInTheDocument();
    expect(
      within(dialog).getByText(
        /^Saved copy from .*Later changes to your entries don't change it\.$/,
      ),
    ).toBeInTheDocument();
    expect(within(dialog).getByText(/Oct 1 was changed after this was saved/)).toBeInTheDocument();
    expect(within(dialog).getByRole('link', { name: 'Create a new report' })).toHaveAttribute(
      'href',
      '/dar?from=2026-09-30&to=2026-10-02',
    );
    expect(within(dialog).getByRole('button', { name: 'Export PDF' })).toBeInTheDocument();
    expect(within(dialog).queryByRole('button', { name: /delete|send/i })).not.toBeInTheDocument();
  });

  it('shows the empty state and the no-results state', async () => {
    api('MEMBER', (url) =>
      url.includes('/dar/saved') ? { status: 200, body: { items: [] } } : undefined,
    );
    renderAt('/dar/saved', <App />);
    expect(await screen.findByText('No saved reports yet')).toBeInTheDocument();
    await userEvent.selectOptions(screen.getByLabelText('Label'), 'LATEST');
    expect(await screen.findByText('No saved reports match these filters')).toBeInTheDocument();
    await userEvent.click(screen.getByRole('button', { name: 'Clear filters' }));
    await waitFor(() => expect(screen.getByText('No saved reports yet')).toBeInTheDocument());
  });
});
