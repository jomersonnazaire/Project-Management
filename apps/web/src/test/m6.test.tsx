const darRoute =
  (r: DarReportDto, extra: Route = () => undefined): Route =>
  (url, init) =>
    extra(url, init) ??
    (/\/dar(\?|$)/.test(url) ? { status: 200, body: { report: r } } : undefined);

describe('TC-R01/R02/R04/R06: report preview', () => {
  it('shows the sample layout, day status and no Send button', async () => {
    api('MEMBER', darRoute(report()));
    renderAt('/dar?from=2026-09-30&to=2026-10-02', <App />);
    const view = await screen.findByTestId('dar-report');
    expect(within(view).getByText('Daily Accomplishment Report')).toBeInTheDocument();
    expect(
      within(view).getByText('Generated range: Sep 30, 2026 to Oct 2, 2026'),
    ).toBeInTheDocument();
    expect(within(view).getByText('Total Activities:').parentElement).toHaveTextContent(
      'Total Activities: 2',
    );
    const heads = within(view)
      .getAllByRole('columnheader')
      .map((h) => h.textContent);
    expect(heads).toEqual([
      'Date',
      'Time In',
      'Time Out',
      'Rendered Hrs',
      'Client Name',
      'Project Name',
      'Activity Type',
      'Location',
      'Billable',
      'Module',
      'Activity Remarks',
    ]);
    expect(within(view).getByText('08:00 AM')).toBeInTheDocument();
    expect(within(view).getByText('Total rendered hours').parentElement).toHaveTextContent('05:07');
    expect(
      within(view).getByText(
        'This is an automated email. Generated by Project Activity Tracker Application.',
      ),
    ).toBeInTheDocument();
    // TC-R10: markup in remarks is text.
    expect(
      within(view).getByText('<script>alert(1)</script> <img src=x onerror=alert(1)>'),
    ).toBeInTheDocument();
    expect(view.querySelector('script, img')).toBeNull();
    // TC-R04: day status, not part of the report.
    const status = screen.getByTestId('dar-day-status');
    expect(status).toHaveTextContent('Sep 30 Submitted');
    expect(status).toHaveTextContent('Oct 1 Reopened by Jomerson Nazaire');
    expect(status).toHaveTextContent('Oct 2 Not submitted');
    expect(status).toHaveTextContent("A running timer isn't included until you press Time out.");
    // TC-R06
    expect(screen.queryByRole('button', { name: /send/i })).not.toBeInTheDocument();
    expect(screen.getByText('Coming with Microsoft sign-in')).toBeInTheDocument();
    expect(
      screen.getByText(/Supervisor: Jomerson Nazaire · CC: hr@xceler8.example/),
    ).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Export PDF' })).toBeInTheDocument();
    expect(screen.getByRole('button', { name: 'Export Excel' })).toBeInTheDocument();
  });

  it('TC-R03: refuses over 31 days and From after To before asking the server', async () => {
    const fetch = api('MEMBER', darRoute(report()));
    renderAt('/dar?from=2026-09-30&to=2026-10-02', <App />);
    await screen.findByTestId('dar-report');
    const from = screen.getByLabelText('From');
    await userEvent.clear(from);
    await userEvent.type(from, '2026-08-01');
    const calls = fetch.mock.calls.length;
    await userEvent.click(screen.getByRole('button', { name: 'Preview' }));
    expect(
      await screen.findByText('The range can be up to 31 days. Pick a shorter range.'),
    ).toBeInTheDocument();
    await userEvent.clear(from);
    await userEvent.type(from, '2026-10-05');
    await userEvent.click(screen.getByRole('button', { name: 'Preview' }));
    expect(await screen.findByText('"From" must be on or before "To".')).toBeInTheDocument();
    expect(fetch.mock.calls.slice(calls).some(([u]) => String(u).includes('/dar?'))).toBe(false);
  });

  it('shows the empty state; Save report confirms with a link', async () => {
    const saved = { id: 's1' } as SavedReportDto;
    const fetch = api(
      'MEMBER',
      darRoute(
        report({ rows: [], totalActivities: 0, totalMinutes: 0, totalRendered: '00:00' }),
        (url, init) =>
          url.endsWith('/dar/saved') && init?.method === 'POST'
            ? { status: 201, body: { item: saved } }
            : undefined,
      ),
    );
    renderAt('/dar?from=2026-09-30&to=2026-10-02', <App />);
    expect(await screen.findByText('No time entries in this range')).toBeInTheDocument();
    await userEvent.click(screen.getByRole('button', { name: 'Save report' }));
    expect(await screen.findByText('View saved reports')).toHaveAttribute('href', '/dar/saved');
    const post = fetch.mock.calls.find(
      ([u, i]) => String(u).endsWith('/dar/saved') && i?.method === 'POST',
    );
    expect(JSON.parse(String(post![1]!.body))).toEqual({ from: '2026-09-30', to: '2026-10-02' });
  });
});

